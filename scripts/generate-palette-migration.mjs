import { writeFile } from 'node:fs/promises';
import { palettes } from '../dist/palettes.js';

const output = new URL('../supabase/migrations/20260919000200_sync_palette_library.sql', import.meta.url);
const roles = ['background', 'surface', 'primary', 'accent', 'text'];
const quote = value => `'${String(value).replaceAll("'", "''")}'`;
const textArray = values => `array[${values.map(quote).join(', ')}]::text[]`;

const paletteRows = palettes.map((palette, index) => `  (${[
  quote(palette.id),
  quote(palette.name),
  quote(palette.description),
  quote(palette.category),
  textArray(palette.tags),
  textArray(palette.useCases),
  'true',
  String(index + 1),
].join(', ')})`).join(',\n');

const colorRows = palettes.flatMap(palette => palette.colors.map((hex, index) => `  (${[
  quote(palette.id),
  String(index + 1),
  quote(roles[index]),
  quote(hex.toUpperCase()),
].join(', ')})`)).join(',\n');

const sql = `-- Generated by scripts/generate-palette-migration.mjs. Do not hand-edit palette rows.
-- palette-count: ${palettes.length}
-- Keep the database source IDs aligned with the static ColorVerse library so
-- private project snapshots can safely retain their source palette reference.

insert into public.palettes (
  id, name, description, category, tags, use_cases, is_published, sort_order
) values
${paletteRows}
on conflict (id) do update set
  name = excluded.name,
  description = excluded.description,
  category = excluded.category,
  tags = excluded.tags,
  use_cases = excluded.use_cases,
  is_published = excluded.is_published,
  sort_order = excluded.sort_order,
  updated_at = now();

insert into public.palette_colors (palette_id, position, role, hex) values
${colorRows}
on conflict (palette_id, position) do update set
  role = excluded.role,
  hex = excluded.hex;

-- Replace the initial snapshot function with strict input validation. RLS and
-- table grants remain the authorization boundary because this is an invoker.
create or replace function public.save_project_snapshot(
  p_project_id uuid,
  p_name text,
  p_context_type text,
  p_source_palette_id text,
  p_colors jsonb,
  p_roles jsonb,
  p_editor_state jsonb
)
returns uuid
language plpgsql
security invoker
set search_path = ''
as \$\$
declare
  v_project_id uuid;
  v_next_version integer;
begin
  if (select auth.uid()) is null then
    raise exception 'Authentication required' using errcode = '42501';
  end if;
  if p_name is null or character_length(trim(p_name)) not between 1 and 120 then
    raise exception 'Project name must be between 1 and 120 characters' using errcode = '22023';
  end if;
  if p_context_type is null or p_context_type not in ('custom', 'website', 'slides', 'social', 'shop', 'brand', 'roomkit', 'editorial') then
    raise exception 'Unsupported project context' using errcode = '22023';
  end if;
  if jsonb_typeof(p_colors) <> 'array' or jsonb_array_length(p_colors) <> 5 then
    raise exception 'A project snapshot requires exactly five colors' using errcode = '22023';
  end if;
  if exists (
    select 1 from jsonb_array_elements_text(p_colors) as color(value)
    where color.value !~ '^#[0-9A-Fa-f]{6}$'
  ) then
    raise exception 'Project colors must use six-digit HEX values' using errcode = '22023';
  end if;
  if p_roles is not null and (jsonb_typeof(p_roles) <> 'object' or octet_length(p_roles::text) > 4096) then
    raise exception 'Invalid project roles' using errcode = '22023';
  end if;
  if p_editor_state is not null and (jsonb_typeof(p_editor_state) <> 'object' or octet_length(p_editor_state::text) > 16384) then
    raise exception 'Invalid editor state' using errcode = '22023';
  end if;
  if p_source_palette_id is not null and not exists (
    select 1 from public.palettes where palettes.id = p_source_palette_id and palettes.is_published = true
  ) then
    raise exception 'Source palette not found' using errcode = '22023';
  end if;

  if p_project_id is null then
    insert into public.projects (user_id, name, context_type, source_palette_id)
    values ((select auth.uid()), trim(p_name), p_context_type, p_source_palette_id)
    returning id into v_project_id;
  else
    update public.projects
    set name = trim(p_name), context_type = p_context_type, source_palette_id = p_source_palette_id
    where id = p_project_id and user_id = (select auth.uid())
    returning id into v_project_id;

    if v_project_id is null then
      raise exception 'Project not found' using errcode = 'P0002';
    end if;
  end if;

  select coalesce(max(version_number), 0) + 1
  into v_next_version
  from public.project_versions
  where project_id = v_project_id;

  insert into public.project_versions (
    project_id, version_number, name, variant_key, colors, roles, editor_state
  ) values (
    v_project_id,
    v_next_version,
    case when v_next_version = 1 then 'Baseline' else 'Version ' || v_next_version end,
    case when v_next_version = 1 then 'baseline' else 'checkpoint' end,
    p_colors,
    coalesce(p_roles, '{}'::jsonb),
    coalesce(p_editor_state, '{}'::jsonb)
  );

  return v_project_id;
end;
\$\$;

revoke all on function public.save_project_snapshot(uuid, text, text, text, jsonb, jsonb, jsonb) from public, anon;
grant execute on function public.save_project_snapshot(uuid, text, text, text, jsonb, jsonb, jsonb) to authenticated;
`;

await writeFile(output, sql);
console.log(`Generated ${palettes.length} palettes and ${palettes.length * 5} colors.`);
